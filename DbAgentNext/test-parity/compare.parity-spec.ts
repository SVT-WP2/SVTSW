import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

import {
    compareCase,
    findParityCase,
    PARITY_SNAPSHOTS_DIR,
    ParityComparison,
    ParityRecordedCase,
    readSnapshot,
    shorten,
} from './utils'


/**
 * Compares two recordings (`snapshots/<left>.json`, `snapshots/<right>.json`; `cpp` and `next` unless
 * `SVT_DB_AGENT_PARITY_LEFT` / `_RIGHT` say otherwise) case by case and writes `snapshots/report.md`. A case
 * passes when the normalised replies are the same, or when the difference is listed in
 * `utils/parity-known-differences.ts` with its decision. Anything else fails: a bug in one of the agents, or a
 * decision that is not written down yet.
 */
const left = process.env.SVT_DB_AGENT_PARITY_LEFT ?? 'cpp'
const right = process.env.SVT_DB_AGENT_PARITY_RIGHT ?? 'next'

describe(`parity: "${left}" vs "${right}"`, () => {

    const leftSnapshot = readSnapshot(left)
    const rightSnapshot = readSnapshot(right)
    const ids = [...new Set([...Object.keys(leftSnapshot.cases), ...Object.keys(rightSnapshot.cases)])]
    const comparisons: ParityComparison[] = []

    afterAll(() => {
        const report = renderReport(comparisons)
        const path = join(PARITY_SNAPSHOTS_DIR, 'report.md')
        writeFileSync(path, report, 'utf8')
        const counts = countVerdicts(comparisons)
        console.info(`[parity] ${ids.length} cases: ${counts.same} same, ${counts.intentional} intentional, `
            + `${counts.different} different, ${counts.missing} missing → ${path}`)
    })

    for (const id of ids) {
        it(id, () => {
            const comparison = compareCase(id, findParityCase(id), leftSnapshot.cases[id], rightSnapshot.cases[id])
            comparisons.push(comparison)
            if (comparison.verdict === 'different' || comparison.verdict === 'missing') {
                const sides = [
                    `${left}: ${describeOutcome(comparison.left)}`,
                    `${right}: ${describeOutcome(comparison.right)}`,
                ]
                throw new Error(`${comparison.verdict}:\n  ${comparison.details.join('\n  ')}\n  ${sides.join('\n  ')}`)
            }
        })
    }

    it('heartbeat', () => {
        expect(rightSnapshot.heartbeat).toEqual(leftSnapshot.heartbeat)
    })

    function renderReport(results: ParityComparison[]): string {
        const counts = countVerdicts(results)
        const lines = [
            `# Parity report: \`${left}\` vs \`${right}\``,
            '',
            `Generated by \`compare.parity-spec.ts\` on ${new Date().toISOString()} from \`snapshots/${left}.json\` `
            + `(recorded ${leftSnapshot.recordedAt}) and \`snapshots/${right}.json\` (recorded ${rightSnapshot.recordedAt}).`,
            '',
            '| Verdict | Cases |',
            '|---|---|',
            `| same | ${counts.same} |`,
            `| intentional (a listed decision) | ${counts.intentional} |`,
            `| different (unexplained) | ${counts.different} |`,
            `| missing on one side | ${counts.missing} |`,
            '',
            `Heartbeat: ${left} ${shorten(leftSnapshot.heartbeat)}, ${right} ${shorten(rightSnapshot.heartbeat)}.`,
            '',
            '## Differences',
            '',
            '| Case | Verdict | Decision | Where |',
            '|---|---|---|---|',
        ]
        for (const result of results.filter((item) => item.verdict !== 'same')) {
            lines.push(`| \`${result.id}\` | ${result.verdict} | ${result.decision ?? ''} | ${escapeCell(result.details.join('<br>'))} |`)
        }
        lines.push('', '## All cases', '', `| Case | Verdict | ${left} | ${right} |`, '|---|---|---|---|')
        for (const result of results) {
            const sides = [result.left, result.right].map((side) => escapeCell(describeOutcome(side)))
            lines.push(`| \`${result.id}\` | ${result.verdict} | ${sides[0]} | ${sides[1]} |`)
        }
        return `${lines.join('\n')}\n`
    }

})

function countVerdicts(results: ParityComparison[]): Record<ParityComparison['verdict'], number> {
    const counts = { same: 0, intentional: 0, different: 0, missing: 0 }
    for (const result of results) {
        counts[result.verdict]++
    }
    return counts
}

/** One line per side for the report: status and error message, or the shape of the data. */
function describeOutcome(recorded?: ParityRecordedCase): string {
    if (!recorded) {
        return '—'
    }
    const { outcome } = recorded
    if (outcome.kind === 'timeout') {
        return `no reply within ${outcome.afterMs} ms`
    }
    if ('raw' in outcome.value) {
        return `not JSON: ${shorten(outcome.value.raw, 60)}`
    }
    const { status, data, error } = outcome.value
    if (status !== 'Success') {
        return `${status}: ${shorten(error?.message?.replace(/^\[[^\]\n]*\]\n/, ''), 100)}`
    }
    return `${status}: ${shorten(data, 100)}`
}

function escapeCell(text: string): string {
    return text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}
